// Compiles a level's ASCII tile grid into a numeric collision map.
// Shared by the client (buildLevel) and the server (headless sim).

export function compileLevelMap(level: LevelDef): GridMap {
    return level.tiles.map(function (line) {
        return line.split("").map(function (ch) {
            return ch === "#" ? 1 : 0;
        });
    });
}

// Mirrors buildLevel's solid geometry (water / trees / rocks).

export function compileLevelSolids(level: LevelDef): Rect[] {
    const solids: Rect[] = [];

    for (const water of level.water) {
        solids.push(water);
    }

    for (const tree of level.trees) {
        solids.push({ x: tree[0] - 10, y: tree[1] - 16, w: 38, h: 52 });
    }

    for (const rock of level.rocks) {
        solids.push({ x: rock[0] - 3, y: rock[1] - 3, w: 32, h: 20 });
    }

    return solids;
}